"""
Writes Data/Generated/GearWeights.lua, the Gear Finder's stat weights (Core/ItemScore.lua), from
Aegis: Pathfinder's own (its Tools/data/stat_weights.json, made by its build_weights.py from the
game's formulas).

    python Tools/build_gear_weights.py <stat_weights.json>

Fetch the file from the Pathfinder repository first, for example:
    gh api repos/Torchlite-bit/Aegis_Pathfinder/contents/Tools/data/stat_weights.json \
        -H "Accept: application/vnd.github.raw" > stat_weights.json

Only the weights Pathfinder works out itself are kept. The stats its build fills in from OctoPawn
(resistances, speeds and Turtle WoW's own stats: build_weights.py's rescale_extras) are left out,
so nothing of OctoPawn's is in the journal; those stats count for nothing here.

Each class's specs keep Pathfinder's order and labels, with the spec it assumes while levelling
before talents say otherwise. 'max' is the set at level 60, 'leveling' the set below it (tanks have
only 'max').
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Data", "Generated", "GearWeights.lua")

# build_weights.py's rescale_extras: OctoPawn's weights, rescaled. Not taken.
FROM_OCTOPAWN = {
    "FORTUNE", "AVOIDANCE", "LIFESTEAL", "RESILIENCE", "MOVEMENT SPEED", "MOUNT SPEED",
    "FIRE RESISTANCE", "FROST RESISTANCE", "SHADOW RESISTANCE", "NATURE RESISTANCE",
    "ARCANE RESISTANCE", "ALL RESISTANCES", "ARMOR PENETRATION", "EXTRA ATTACK",
    "ATTACK POWER UNDEAD", "SPELL DAMAGE UNDEAD", "HEALTH PER 5",
}

# Pathfinder's ItemScore.lua: the spec a class levels as with no talents spent, and names to show.
LEVELLING_SPEC = {
    "WARRIOR": "Arms", "PALADIN": "Retribution", "HUNTER": "BeastMastery", "ROGUE": "Combat",
    "PRIEST": "Shadow", "SHAMAN": "Enhancement", "MAGE": "Frost", "WARLOCK": "Affliction",
    "DRUID": "FeralCat",
}
SPEC_LABEL = {
    "BeastMastery": "Beast Mastery", "FeralCat": "Feral (cat)", "FeralBear": "Feral (bear)",
    "EnhancementTank": "Enhancement (tank)",
}
CLASS_ORDER = ["WARRIOR", "PALADIN", "HUNTER", "ROGUE", "PRIEST", "SHAMAN", "MAGE", "WARLOCK", "DRUID"]


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def weights(table):
    kept = sorted((k, v) for k, v in (table or {}).items() if k not in FROM_OCTOPAWN and v)
    return "{ " + ", ".join("[{}] = {}".format(lua_string(k), repr(v)) for k, v in kept) + " }"


def main(path):
    with open(path, encoding="utf-8") as handle:
        specs = json.load(handle)["specs"]
    by_class = {}
    for key, entry in specs.items():
        by_class.setdefault(entry["class"], []).append(entry)
    lines = [
        "-- Generated by Tools/build_gear_weights.py from Aegis: Pathfinder's stat weights. Do not edit.",
        "-- Per class and spec: a point of each stat, in the spec's unit (attack power, spell damage,",
        "-- healing or Stamina). 'max' is the set at level 60, 'leveling' the set below it.",
        "local _, ns = ...",
        "",
        "ns.GEAR_WEIGHTS = {",
    ]
    for cls in CLASS_ORDER:
        entries = by_class.get(cls, [])
        lines.append("\t{} = {{".format(cls))
        lines.append("\t\tlevelling = {},".format(lua_string(LEVELLING_SPEC[cls])))
        lines.append("\t\torder = {{ {} }},".format(", ".join(lua_string(e["spec"]) for e in entries)))
        for e in entries:
            spec = e["spec"]
            lines.append("\t\t{} = {{".format(spec))
            lines.append("\t\t\tlabel = {}, role = {}, unit = {},".format(
                lua_string(SPEC_LABEL.get(spec, spec)), lua_string(e.get("role", "")), lua_string(e.get("unit", ""))))
            if e.get("leveling"):
                lines.append("\t\t\tleveling = {},".format(weights(e["leveling"])))
            lines.append("\t\t\tmax = {},".format(weights(e["max"])))
            lines.append("\t\t},")
        lines.append("\t},")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")
    print("wrote {}: {} specs".format(OUT, len(specs)))
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(1)
    sys.exit(main(sys.argv[1]))
