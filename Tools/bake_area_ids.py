"""Bakes /aegis areas scans into Data/Generated/AreaIDs.lua.

/aegis areas, on an English client, saves the client's ids for each English area name the
journal uses (AegisJournalDB.areaIDs). This reads those scans from the player's saved file and
the testers' (Recordings/<name>/), adds them to the ids already baked, and writes the file the
addon loads: from the ids, every client names the journal's areas in its own language
(Core/Areas.lua). Ids already baked are kept, so a scan that found fewer loses nothing.

    python Tools/bake_area_ids.py
"""

import glob
import os
import sys

import build_data
from build_data import AEGIS_SAVED, RECORDINGS, ROOT, lua, read, table_from_block

OUT = os.path.join(ROOT, "Data", "Generated", "AreaIDs.lua")
HEADER = ("-- Generated by Tools/bake_area_ids.py from /aegis areas on an English client: the client's ids\n"
          "-- for each English area name the journal uses, from which every client names them in its own\n"
          "-- language (Core/Areas.lua). Do not edit by hand.\n\n"
          "local _, ns = ...\n\n")


def baked():
    """The ids in the file now: {name: [ids]}."""
    if not os.path.exists(OUT) or "ns.AREA_IDS = {" not in read(OUT):
        return {}
    found = table_from_block(OUT, "ns.AREA_IDS = {")
    return {name: sorted(ids.values() if isinstance(ids, dict) else ids) for name, ids in (found or {}).items()}


def scans():
    """Every saved /aegis areas scan: (path, {name: [ids]})."""
    files = sorted(glob.glob(AEGIS_SAVED)) + glob.glob(os.path.join(RECORDINGS, "**", "Aegis_Forever_Instance_Journal.lua"),
                                                     recursive=True)
    for path in files:
        if '["areaIDs"] = {' not in read(path):
            continue
        scan = table_from_block(path, '["areaIDs"] = {') or {}
        if scan.get("locale") not in ("enUS", "enGB"):
            print("skipped (not an English client): %s" % path)
            continue
        found = scan.get("found") or {}
        yield path, {name: list(ids.values() if isinstance(ids, dict) else ids) for name, ids in found.items()}


def used_names():
    """Every English area name the journal uses, as Core/Areas.lua lists them (the addon run in Lua)."""
    import io
    import smoke_test
    scenario = os.path.join(ROOT, "Tools", "area_names.lua")
    buf, real = io.StringIO(), sys.stdout
    sys.stdout = buf
    try:
        smoke_test.run_pass(scenario)
    finally:
        sys.stdout = real
    return [line[len("AREA "):] for line in buf.getvalue().splitlines() if line.startswith("AREA ")]


def full_lists():
    """Every saved full list of the client's areas (AegisJournalDB.allAreas: id -> name, from a /run
    line on an English client): (path, {name: [ids]})."""
    files = sorted(glob.glob(AEGIS_SAVED)) + glob.glob(os.path.join(RECORDINGS, "**", "Aegis_Forever_Instance_Journal.lua"),
                                                     recursive=True)
    for path in files:
        if '["allAreas"] = {' not in read(path):
            continue
        names = table_from_block(path, '["allAreas"] = {') or {}
        by_name = {}
        for area_id, name in (names.items() if isinstance(names, dict) else enumerate(names, 1)):
            if isinstance(name, str):
                by_name.setdefault(name, []).append(int(area_id))
        yield path, by_name


def main():
    ids = baked()
    before = sum(len(v) for v in ids.values())
    for path, found in scans():
        for name, new in found.items():
            ids[name] = sorted(set(ids.get(name, [])) | {int(i) for i in new})
        print("read %d names from %s" % (len(found), path))
    lists = list(full_lists())
    if lists:
        wanted = used_names()
        for path, by_name in lists:
            hits = [name for name in wanted if name in by_name]
            for name in hits:
                ids[name] = sorted(set(ids.get(name, [])) | set(by_name[name]))
            print("found %d of the journal's %d area names among the %d areas listed in %s" % (
                len(hits), len(wanted), sum(len(v) for v in by_name.values()), path))
            missing = [name for name in wanted if name not in by_name]
            if missing:
                print("not listed: " + ", ".join(missing))
    build_data.write(os.path.basename(OUT), HEADER + "ns.AREA_IDS = %s\n" % lua(dict(sorted(ids.items()))),
                     folder=os.path.dirname(OUT))
    print("%d area names, %d ids (%d before)" % (len(ids), sum(len(v) for v in ids.values()), before))
    return 0


if __name__ == "__main__":
    sys.exit(main())
