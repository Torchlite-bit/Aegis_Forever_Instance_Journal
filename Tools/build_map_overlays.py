"""
Writes Data/Generated/MapOverlays.lua, every zone's explorable map pieces, for the world map's
"Show unexplored areas" choice (UI/ZoneMap.lua). The client lists only the pieces a character
has explored (C_MapExplorationInfo.GetExploredMapTextures), so the rest come from its map tables.

    python Tools/build_map_overlays.py <folder>

The folder holds three of the client's tables as CSV, as wago.tools exports them for the
client's build (https://wago.tools/db2/<table>/csv?build=<build>):
  WorldMapOverlay.csv      each piece: its map art, size and offset in the map's pixels
  WorldMapOverlayTile.csv  the textures a piece is cut into, by row and column
  UiMapXMapArt.csv         which map (uiMapID) shows which map art

Each zone gets a list of pieces, each { width, height, offsetX, offsetY, file, file, ... } with
its textures row by row, as the client's own MapExplorationPinMixin draws them.
"""

import csv
import os
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Data", "Generated", "MapOverlays.lua")
BUILD = "1.60.1.70374"


def rows(folder, table):
    with open(os.path.join(folder, table + ".csv"), encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def main(folder):
    maps_by_art = defaultdict(list)
    for row in rows(folder, "UiMapXMapArt"):
        maps_by_art[row["UiMapArtID"]].append(int(row["UiMapID"]))

    tiles = defaultdict(list)
    for row in rows(folder, "WorldMapOverlayTile"):
        if row["LayerIndex"] == "0":
            tiles[row["WorldMapOverlayID"]].append((int(row["RowIndex"]), int(row["ColIndex"]), int(row["FileDataID"])))

    zones = defaultdict(list)
    for row in rows(folder, "WorldMapOverlay"):
        files = [file for _, _, file in sorted(tiles.get(row["ID"], []))]
        if not files:
            continue
        piece = [int(row[key]) for key in ("TextureWidth", "TextureHeight", "OffsetX", "OffsetY")] + files
        for map_id in maps_by_art.get(row["UiMapArtID"], []):
            zones[map_id].append(piece)

    lines = [
        "-- Generated by Tools/build_map_overlays.py from the client's map tables (WorldMapOverlay,",
        "-- WorldMapOverlayTile, UiMapXMapArt) for build %s, as wago.tools exports them. Do not edit." % BUILD,
        "-- Each zone's explorable pieces: { width, height, offsetX, offsetY, texture files row by row }.",
        "local _, ns = ...",
        "",
        "ns.MAP_OVERLAYS = {",
    ]
    for map_id in sorted(zones):
        lines.append("\t[%d] = {" % map_id)
        for piece in sorted(zones[map_id], key=lambda piece: (piece[3], piece[2])):
            lines.append("\t\t{ %s }," % ", ".join(str(value) for value in piece))
        lines.append("\t},")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")
    print("wrote %s: %d zones, %d pieces" % (OUT, len(zones), sum(len(pieces) for pieces in zones.values())))
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(1)
    sys.exit(main(sys.argv[1]))
